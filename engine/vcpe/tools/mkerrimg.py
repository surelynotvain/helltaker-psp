#!/usr/bin/env python3
"""engineassets/errorscreenimage.* -> src/vcpe_errimg.h: the picture vcpe_fatal() shows in the bottom-right corner
of the start-up error screen, scaled down and stored as RGB565 (no game data needed to show it).
Usage: mkerrimg.py [IMAGE] [WIDTH]"""
import sys
from pathlib import Path
from PIL import Image
root = Path(__file__).resolve().parents[1]
src = Path(sys.argv[1]) if len(sys.argv) > 1 else root / 'engineassets/errorscreenimage.jpg'
w = int(sys.argv[2]) if len(sys.argv) > 2 else 136
im = Image.open(src).convert('RGB')
h = round(im.height * w / im.width)
im = im.resize((w, h), Image.Resampling.LANCZOS)
px = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in zip(*[iter(im.tobytes())] * 3)]
out = ['/* generated by tools/mkerrimg.py from %s - do not edit */' % src.name,
       '#define VCPE_ERRIMG_W %d' % w, '#define VCPE_ERRIMG_H %d' % h,
       'static const unsigned short vcpe_errimg[%d] = {' % len(px)]
for i in range(0, len(px), 16):
    out.append('    ' + ', '.join('0x%04x' % v for v in px[i:i + 16]) + ',')
out.append('};')
(root / 'src/vcpe_errimg.h').write_text('\n'.join(out) + '\n')
print('vcpe_errimg.h: %dx%d, %d bytes' % (w, h, len(px) * 2))
