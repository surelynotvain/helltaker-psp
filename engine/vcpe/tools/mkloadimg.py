#!/usr/bin/env python3
"""engineassets/wow.gif -> src/vcpe_loadimg.h: the animation the standard loading screen (vcpe_load) plays in the
bottom-right corner. Like the error screen's picture it is built into the engine, so every game gets it without
game data. Frames are scaled, every STEP-th frame kept (their GIF durations summed, so it plays at the same speed),
and stored as 8-bit indexed pixels with one shared 256-colour palette (a GU T8 texture, rows 16-byte aligned).
Usage: mkloadimg.py [GIF] [SIZE] [STEP]     (defaults: engineassets/wow.gif, 96, 2)"""
import sys
from pathlib import Path
from PIL import Image, ImageSequence
root = Path(__file__).resolve().parents[1]
src = Path(sys.argv[1]) if len(sys.argv) > 1 else root / 'engineassets/wow.gif'
size = int(sys.argv[2]) if len(sys.argv) > 2 else 96
step = int(sys.argv[3]) if len(sys.argv) > 3 else 2
assert size % 16 == 0, 'SIZE must be a multiple of 16 (T8 rows)'
gif = Image.open(src)
frames, durs = [], []
for i, f in enumerate(ImageSequence.Iterator(gif)):
    d = f.info.get('duration', 100) or 100
    if i % step == 0:
        im = f.convert('RGB')
        w, h = im.size
        s = min(w, h)   # centre square
        im = im.crop(((w - s) // 2, (h - s) // 2, (w - s) // 2 + s, (h - s) // 2 + s))
        frames.append(im.resize((size, size), Image.Resampling.LANCZOS))
        durs.append(d)
    else:
        durs[-1] += d
# one palette for all frames: quantize a montage, then map every frame to it
mont = Image.new('RGB', (size, size * len(frames)))
for i, f in enumerate(frames):
    mont.paste(f, (0, i * size))
pal_img = mont.quantize(256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
idx = mont.quantize(palette=pal_img, dither=Image.Dither.FLOYDSTEINBERG).tobytes()
pal = pal_img.getpalette()[:768] + [0] * (768 - len(pal_img.getpalette()[:768]))
clut = [0xFF000000 | (pal[i * 3 + 2] << 16) | (pal[i * 3 + 1] << 8) | pal[i * 3] for i in range(256)]
out = ['/* generated by tools/mkloadimg.py from %s - do not edit */' % src.name,
       '#define VCPE_LOADIMG_SIZE %d' % size, '#define VCPE_LOADIMG_FRAMES %d' % len(frames),
       'static const unsigned short vcpe_loadimg_ms[%d] = {%s};' % (len(durs), ', '.join(map(str, durs))),
       'static const unsigned int __attribute__((aligned(16))) vcpe_loadimg_clut[256] = {']
for i in range(0, 256, 8):
    out.append('    ' + ', '.join('0x%08x' % v for v in clut[i:i + 8]) + ',')
out.append('};')
out.append('static const unsigned char __attribute__((aligned(16))) vcpe_loadimg[%d] = {' % len(idx))
for i in range(0, len(idx), 32):
    out.append('    ' + ','.join(str(b) for b in idx[i:i + 32]) + ',')
out.append('};')
(root / 'src/vcpe_loadimg.h').write_text('\n'.join(out) + '\n')
print('vcpe_loadimg.h: %d frames %dx%d, %d ms loop, %d KB' % (len(frames), size, size, sum(durs), (len(idx) + 1024) // 1024))
